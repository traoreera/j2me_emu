uint8_t g_glyph[256][5];
bool g_init = false;

// Glyphe dessiné à la main : 7 lignes de 5 caractères ('#' = pixel allumé).
void setRows(unsigned char c, const char *const r[7])
{
    for (int col = 0; col < 5; col++)
    {
        uint8_t b = 0;
        for (int row = 0; row < 7; row++)
            if (r[row][col] == '#')
                b |= static_cast<uint8_t>(1u << row);
        g_glyph[c][col] = b;
    }
}
void copyOf(unsigned char dst, unsigned char src) { std::memcpy(g_glyph[dst], g_glyph[src], 5); }

// Marques d'accent (colonnes, rangées 0 et 1).
enum Mark { NONE, GRAVE, ACUTE, CIRC, DIAER, TILDE, RING, CEDIL };
void applyMark(unsigned char dst, Mark m)
{
    static const uint8_t marks[8][5] = {
        {0, 0, 0, 0, 0},
        {0, 1, 2, 0, 0}, // grave  `
        {0, 0, 2, 1, 0}, // aigu   ´
        {0, 2, 1, 2, 0}, // circonflexe ^
        {0, 1, 0, 1, 0}, // tréma  ¨
        {2, 1, 2, 1, 0}, // tilde  ~
        {0, 3, 0, 3, 0}, // rond   °
        {0, 0, 0, 0, 0},
    };
    for (int col = 0; col < 5; col++)
        g_glyph[dst][col] |= marks[m][col];
    if (m == CEDIL) // cédille : petite queue sous la lettre (colonne du milieu, dernière rangée)
        g_glyph[dst][2] |= 0x40;
}
void compose(unsigned char dst, char base, Mark m)
{
    copyOf(dst, static_cast<unsigned char>(base));
    applyMark(dst, m);
}

